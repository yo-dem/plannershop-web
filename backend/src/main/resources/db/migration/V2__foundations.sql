-- Foundations: tenants (businesses), users, per-tenant roles, refresh tokens.
--
-- Conventions for every table (see docs/SPECIFICA.md §6):
--   created_at / updated_at  auditing
--   version                  optimistic locking (JPA @Version)
--   deleted_at / deleted_by  soft delete: rows are never physically deleted
-- Unique constraints apply only to non-deleted rows (partial indexes).

CREATE TABLE tenant (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text        NOT NULL,
    active      boolean     NOT NULL DEFAULT true,
    time_zone   text        NOT NULL DEFAULT 'Europe/Rome',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    version     bigint      NOT NULL DEFAULT 0,
    deleted_at  timestamptz,
    deleted_by  bigint
);

CREATE TABLE app_user (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 text        NOT NULL,
    password_hash         text        NOT NULL,
    name                  text        NOT NULL,
    active                boolean     NOT NULL DEFAULT true,
    superadmin            boolean     NOT NULL DEFAULT false,
    must_change_password  boolean     NOT NULL DEFAULT false,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    version               bigint      NOT NULL DEFAULT 0,
    deleted_at            timestamptz,
    deleted_by            bigint
);

CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email)) WHERE deleted_at IS NULL;

-- A user's membership in a tenant, with the role they have there.
CREATE TABLE membership (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user (id),
    tenant_id   bigint      NOT NULL REFERENCES tenant (id),
    role        text        NOT NULL CHECK (role IN ('ADMIN', 'OPERATOR')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    version     bigint      NOT NULL DEFAULT 0,
    deleted_at  timestamptz,
    deleted_by  bigint
);

CREATE UNIQUE INDEX ux_membership_user_tenant ON membership (user_id, tenant_id) WHERE deleted_at IS NULL;
CREATE INDEX ix_membership_tenant ON membership (tenant_id);

-- Refresh tokens: only the SHA-256 hash is stored, never the token itself.
-- Not domain data: expired or revoked tokens are kept as history.
CREATE TABLE refresh_token (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user (id),
    tenant_id   bigint      REFERENCES tenant (id),
    token_hash  text        NOT NULL UNIQUE,
    user_agent  text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz
);

CREATE INDEX ix_refresh_token_user ON refresh_token (user_id);
