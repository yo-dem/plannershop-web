-- Tenant catalog: products (formerly TProdotti) and services (formerly TServizi).
-- See SPECIFICA §6.3, §6.4 and §7.1 (prices).

CREATE TABLE product (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint        NOT NULL REFERENCES tenant (id),
    stock_date   date,
    brand        text          NOT NULL,
    description  text          NOT NULL,
    quantity     integer       NOT NULL CHECK (quantity >= 0),
    vat_rate     numeric(5,2)  NOT NULL CHECK (vat_rate BETWEEN 0 AND 100),
    net_price    numeric(12,2) NOT NULL CHECK (net_price >= 0),
    gross_price  numeric(12,2) NOT NULL CHECK (gross_price >= 0),
    sale_price   numeric(12,2) NOT NULL CHECK (sale_price >= 0),
    notes        text,
    created_at   timestamptz   NOT NULL DEFAULT now(),
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    version      bigint        NOT NULL DEFAULT 0,
    deleted_at   timestamptz,
    deleted_by   bigint
);

-- List sorted by brand and description (non-deleted products only).
CREATE INDEX product_tenant_brand_ix ON product (tenant_id, lower(brand), lower(description))
    WHERE deleted_at IS NULL;

-- "service" would be ambiguous in the code (Spring @Service): the table is service_item.
CREATE TABLE service_item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint        NOT NULL REFERENCES tenant (id),
    name         text          NOT NULL,
    description  text          NOT NULL,
    vat_rate     numeric(5,2)  NOT NULL CHECK (vat_rate BETWEEN 0 AND 100),
    net_price    numeric(12,2) NOT NULL CHECK (net_price >= 0),
    gross_price  numeric(12,2) NOT NULL CHECK (gross_price >= 0),
    sale_price   numeric(12,2) NOT NULL CHECK (sale_price >= 0),
    notes        text,
    created_at   timestamptz   NOT NULL DEFAULT now(),
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    version      bigint        NOT NULL DEFAULT 0,
    deleted_at   timestamptz,
    deleted_by   bigint
);

CREATE INDEX service_item_tenant_name_ix ON service_item (tenant_id, lower(name))
    WHERE deleted_at IS NULL;
