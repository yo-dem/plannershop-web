-- Settings of a tenant (formerly TOpzioni), one row per tenant, created on the
-- first save: until then the defaults below apply. See SPECIFICA §6.9.
-- The other groups (appearance, agenda, email) will be added as new columns.

CREATE TABLE tenant_settings (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   bigint      NOT NULL UNIQUE REFERENCES tenant (id),
    -- products list: quantity <= out_of_stock_threshold → red,
    -- quantity <= low_stock_threshold → orange
    out_of_stock_threshold      integer     NOT NULL DEFAULT 0,
    low_stock_threshold         integer     NOT NULL DEFAULT 10,
    created_at                  timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),
    version                     bigint      NOT NULL DEFAULT 0,
    deleted_at                  timestamptz,
    deleted_by                  bigint,
    CONSTRAINT tenant_settings_stock_ck
        CHECK (out_of_stock_threshold >= 0 AND low_stock_threshold >= out_of_stock_threshold)
);
