-- Customers of a tenant (formerly TClienti). See SPECIFICA §6.2.
-- The birthday is day + month, without a year (as in the old desktop app).

CREATE TABLE customer (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint      NOT NULL REFERENCES tenant (id),
    first_name   text        NOT NULL,
    last_name    text        NOT NULL,
    birth_day    smallint,
    birth_month  smallint,
    phone        text,
    email        text,
    address      text,
    notes        text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    version      bigint      NOT NULL DEFAULT 0,
    deleted_at   timestamptz,
    deleted_by   bigint,
    -- day and month: both present or both absent, within a valid range
    CONSTRAINT customer_birthday_ck CHECK (
        (birth_day IS NULL AND birth_month IS NULL)
        OR (birth_day BETWEEN 1 AND 31 AND birth_month BETWEEN 1 AND 12)
    )
);

-- List sorted by last and first name (non-deleted customers only).
CREATE INDEX customer_tenant_name_ix ON customer (tenant_id, lower(last_name), lower(first_name))
    WHERE deleted_at IS NULL;

-- Birthdays of the month.
CREATE INDEX customer_tenant_birthday_ix ON customer (tenant_id, birth_month, birth_day)
    WHERE deleted_at IS NULL;
