-- Catalogo dell'attività: prodotti (ex TProdotti) e servizi (ex TServizi).
-- Vedi SPECIFICA §6.3, §6.4 e §7.1 (prezzi).

CREATE TABLE prodotto (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint        NOT NULL REFERENCES tenant (id),
    data_carico    date,
    marca          text          NOT NULL,
    descrizione    text          NOT NULL,
    quantita       integer       NOT NULL CHECK (quantita >= 0),
    aliquota_iva   numeric(5,2)  NOT NULL CHECK (aliquota_iva BETWEEN 0 AND 100),
    prezzo_netto   numeric(12,2) NOT NULL CHECK (prezzo_netto >= 0),
    prezzo_ivato   numeric(12,2) NOT NULL CHECK (prezzo_ivato >= 0),
    prezzo_vendita numeric(12,2) NOT NULL CHECK (prezzo_vendita >= 0),
    note           text,
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    version        bigint        NOT NULL DEFAULT 0,
    deleted_at     timestamptz,
    deleted_by     bigint
);

-- Elenco ordinato per marca e descrizione (solo prodotti non eliminati).
CREATE INDEX prodotto_tenant_marca_ix ON prodotto (tenant_id, lower(marca), lower(descrizione))
    WHERE deleted_at IS NULL;

CREATE TABLE servizio (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint        NOT NULL REFERENCES tenant (id),
    nome           text          NOT NULL,
    descrizione    text          NOT NULL,
    aliquota_iva   numeric(5,2)  NOT NULL CHECK (aliquota_iva BETWEEN 0 AND 100),
    prezzo_netto   numeric(12,2) NOT NULL CHECK (prezzo_netto >= 0),
    prezzo_ivato   numeric(12,2) NOT NULL CHECK (prezzo_ivato >= 0),
    prezzo_vendita numeric(12,2) NOT NULL CHECK (prezzo_vendita >= 0),
    note           text,
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    version        bigint        NOT NULL DEFAULT 0,
    deleted_at     timestamptz,
    deleted_by     bigint
);

CREATE INDEX servizio_tenant_nome_ix ON servizio (tenant_id, lower(nome))
    WHERE deleted_at IS NULL;
