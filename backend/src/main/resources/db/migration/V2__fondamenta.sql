-- Fondamenta: attività (tenant), utenti, ruoli per attività, refresh token.
--
-- Convenzioni valide per tutte le tabelle (vedi docs/SPECIFICA.md §6):
--   created_at / updated_at  tracciamento
--   version                  optimistic locking (JPA @Version)
--   deleted_at / deleted_by  eliminazione logica: nessuna riga si cancella davvero
-- I vincoli di unicità valgono solo per le righe non eliminate (indici parziali).

CREATE TABLE tenant (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         text        NOT NULL,
    attivo       boolean     NOT NULL DEFAULT true,
    fuso_orario  text        NOT NULL DEFAULT 'Europe/Rome',
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    version      bigint      NOT NULL DEFAULT 0,
    deleted_at   timestamptz,
    deleted_by   bigint
);

CREATE TABLE app_user (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                   text        NOT NULL,
    password_hash           text        NOT NULL,
    nome                    text        NOT NULL,
    attivo                  boolean     NOT NULL DEFAULT true,
    superadmin              boolean     NOT NULL DEFAULT false,
    deve_cambiare_password  boolean     NOT NULL DEFAULT false,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    version                 bigint      NOT NULL DEFAULT 0,
    deleted_at              timestamptz,
    deleted_by              bigint
);

CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email)) WHERE deleted_at IS NULL;

-- Appartenenza di un utente a un'attività, con il ruolo che ha in quell'attività.
CREATE TABLE membership (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user (id),
    tenant_id   bigint      NOT NULL REFERENCES tenant (id),
    ruolo       text        NOT NULL CHECK (ruolo IN ('ADMIN', 'OPERATORE')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    version     bigint      NOT NULL DEFAULT 0,
    deleted_at  timestamptz,
    deleted_by  bigint
);

CREATE UNIQUE INDEX ux_membership_user_tenant ON membership (user_id, tenant_id) WHERE deleted_at IS NULL;
CREATE INDEX ix_membership_tenant ON membership (tenant_id);

-- Refresh token: si salva solo l'hash SHA-256, mai il token in chiaro.
-- Non è un dato di dominio: i token scaduti o revocati restano come storico.
CREATE TABLE refresh_token (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES app_user (id),
    tenant_id   bigint      REFERENCES tenant (id),
    token_hash  text        NOT NULL UNIQUE,
    user_agent  text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz
);

CREATE INDEX ix_refresh_token_user ON refresh_token (user_id);
