-- Clienti dell'attività (ex TClienti). Vedi SPECIFICA §6.2.
-- Il compleanno è giorno + mese, senza anno (come nel vecchio programma).

CREATE TABLE cliente (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint      NOT NULL REFERENCES tenant (id),
    nome           text        NOT NULL,
    cognome        text        NOT NULL,
    giorno_nascita smallint,
    mese_nascita   smallint,
    telefono       text,
    email          text,
    indirizzo      text,
    note           text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    version        bigint      NOT NULL DEFAULT 0,
    deleted_at     timestamptz,
    deleted_by     bigint,
    -- giorno e mese: entrambi presenti o entrambi assenti, in un intervallo valido
    CONSTRAINT cliente_compleanno_ck CHECK (
        (giorno_nascita IS NULL AND mese_nascita IS NULL)
        OR (giorno_nascita BETWEEN 1 AND 31 AND mese_nascita BETWEEN 1 AND 12)
    )
);

-- Elenco ordinato per cognome e nome (solo clienti non eliminati).
CREATE INDEX cliente_tenant_nome_ix ON cliente (tenant_id, lower(cognome), lower(nome))
    WHERE deleted_at IS NULL;

-- Compleanni del mese.
CREATE INDEX cliente_tenant_compleanno_ix ON cliente (tenant_id, mese_nascita, giorno_nascita)
    WHERE deleted_at IS NULL;
